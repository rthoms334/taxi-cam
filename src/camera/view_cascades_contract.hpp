// Optional, reviewed proof of the per-view sun-shadow slice count. Captured
// 2026-10-04 from the Store image (PE timestamp 1787653788, SizeOfImage
// 235963904), two ranges:
// - CascadeSetup: the first 206 bytes of the scene's per-view cascade setup
//   (World_Z vtable slot 23, called by View::PrepareScene on the simulator main
//   thread with RCX = World, RDX = render context). After the shadow check it
//   calls the slice reader with the context and stores its result as the view's
//   cascade count; the scene pass then culls and draws one shadow list per slice.
// - SliceReader: the first 185 bytes of that reader. It loads the view from
//   context+0xC10 and the slice count from the float at view+0x47C (truncated,
//   clamped to 4). The simulator rewrites that field from its defaults for
//   every view every frame before PrepareScene, so a persistent write from the
//   camera manager update is overwritten.
// Only decoded external PC-relative operands vary. It is resolved after the
// camera contract with the renderer cache pinned to that contract's binding.
// An unresolved range leaves the cascade control unavailable and never refuses
// the camera contract.
